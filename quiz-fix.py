def load(slug):
    with open(os.path.join(BASE, slug + ".json")) as f:
        return json.load(f)

def save(slug, data):
    with open(os.path.join(BASE, slug + ".json"), "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")

def main():
    data = {s: load(s) for s in SLUGS}
    changed = []  # (slug, day, qidx, old_q, new_q, kind)

    # 1. Moves: copy a good block quiz onto the day it actually fits.
    for slug, from_day, to_day in MOVES:
        src = copy.deepcopy(data[slug]["days"][from_day - 1]["quiz"])
        dst = data[slug]["days"][to_day - 1]
        for i, (old, new) in enumerate(zip(dst["quiz"], src)):
            changed.append((slug, to_day, i, old["q"], new["q"], "moved-quiz"))
        dst["quiz"] = src

    # 2. Q1 distractor swaps (animation-2d, beat-making): keep q/answer/explain.
    for (slug, qtext), new_opts in Q1OPTS.items():
        for day in data[slug]["days"]:
            q0 = day["quiz"][0]
            if q0["q"] == qtext:
                old_opts = list(q0["options"])
                assert new_opts[q0["answer"]] == old_opts[q0["answer"]], (slug, day["day"], qtext)
                assert len(set(o.strip().lower() for o in new_opts)) == 4
                q0["options"] = list(new_opts)
                changed.append((slug, day["day"], 0, qtext, qtext, "distractors"))

    # 3. Full question replacements.
    for (slug, day_no, qi), newq in FIXES.items():
        old = data[slug]["days"][day_no - 1]["quiz"][qi]
        changed.append((slug, day_no, qi, old["q"], newq["q"], "rewrite"))
        data[slug]["days"][day_no - 1]["quiz"][qi] = copy.deepcopy(newq)

    # 4. Validate + check nothing outside quizzes changed vs /tmp backups.
    import collections
    report = {"changed": changed, "per_file": collections.Counter(), "kinds": collections.Counter()}
    for slug, day_no, qi, old_q, new_q, kind in changed:
        report["per_file"][slug] += 1
        report["kinds"][kind] += 1
    for slug in SLUGS:
        d = data[slug]
        assert len(d["days"]) == 30, slug
        for day in d["days"]:
            assert len(day["quiz"]) == 3, (slug, day["day"])
            for q in day["quiz"]:
                assert set(q.keys()) == {"q", "options", "answer", "explain"}, (slug, day["day"], q)
                assert len(q["options"]) == 4 and all(isinstance(o, str) and o.strip() for o in q["options"])
                assert len(set(o.strip().lower() for o in q["options"])) == 4, (slug, day["day"], q["q"])
                assert 0 <= q["answer"] <= 3
                assert isinstance(q["explain"], str) and q["explain"].strip()
                assert isinstance(q["q"], str) and q["q"].strip()
        # non-quiz fields identical to backup
        bak = json.load(open(f"/tmp/backup-{slug}.json"))
        for bd, dd in zip(bak["days"], d["days"]):
            for k, v in bd.items():
                if k != "quiz":
                    assert v == dd[k], (slug, dd["day"], k)
        assert set(bak.keys()) == set(d.keys()), slug
        save(slug, d)
    with open("/tmp/quiz-fix-report.json", "w") as f:
        json.dump({"per_file": dict(report["per_file"]), "kinds": dict(report["kinds"]),
                   "changed": changed}, f, indent=2)
    print("FILES:", len(SLUGS))
    print("TOTAL CHANGED QUESTIONS:", len(changed))
    print("KINDS:", dict(report["kinds"]))
    print("PER FILE:", dict(report["per_file"]))
    # template re-scan
    for slug in SLUGS:
        d = data[slug]
        n_key = sum(1 for day in d["days"] for q in day["quiz"] if "key point of today's lesson" in q["q"].lower())
        n_ess = sum(1 for day in d["days"] for q in day["quiz"] if "most essential for" in q["q"].lower())
        n_goal = sum(1 for day in d["days"] for q in day["quiz"] if "main goal of today's lesson" in q["q"].lower() or "goal of today's lesson" in q["q"].lower() or "did today's lesson focus on" in q["q"].lower())
        n_first = sum(1 for day in d["days"] for q in day["quiz"] if "first step in today's lesson" in q["q"].lower())
        n_always = sum(1 for day in d["days"] for q in day["quiz"] if "what should you always do" in q["q"].lower())
        if n_key or n_ess or n_goal or n_always:
            print(f"REMAINING TEMPLATES {slug}: key={n_key} ess={n_ess} goal={n_goal} always={n_always}")
        # distinct quiz sets per file (repeat check)
        sigs = [tuple(q["q"] for q in day["quiz"]) for day in d["days"]]
        print(f"{slug}: distinct quiz sets {len(set(sigs))}/30, first-step Qs left {n_first}")
    print("VALIDATION OK — all files parse, 30 days, 3 Q/day, answers 0-3, explanations present, non-quiz fields unchanged.")

